#!/usr/bin/env python3
"""Generates src/sites.inc from the MWCrashFix patch table (dllmain.c, aPatches[]).
Usage: gen_sites.py <MWCrashFix dllmain.c> <out sites.inc>"""
import re, sys
src = open(sys.argv[1], encoding='utf-8').read()
rows = re.findall(r'\{\s*(0x[0-9A-Fa-f]+),\s*([67]),\s*\{([^}]*)\}\s*\}', src)
out = ['/* Generated by tools/gen_sites.py from MWCrashFix (x0reaxeax) aPatches[]. Do not edit. */',
       '/* Each entry: address of "mov dword ptr [reg(+0)], imm32" in speed.exe v1.3 and its length. */']
seen = set()
for a, n, b in rows:
    a = int(a, 16); n = int(n)
    bb = [int(x, 16) for x in b.split(',') if x.strip()]
    assert len(bb) == n and bb[0] == 0xC7, hex(a)
    imm = bb[-4:]
    assert imm == [0x28, 0xa8, 0x8a, 0x00], hex(a)
    assert (n == 7) == (bb[1] == 0x45), hex(a)   # [ebp+0x0] needs a disp8
    assert a not in seen; seen.add(a)
    out.append('    { 0x%08X, %d, 0x%02X },' % (a, n, bb[1]))
assert len(seen) == 434, len(seen)
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('sites:', len(seen))
